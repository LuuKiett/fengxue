// Parses a TOCFL-style vocabulary PDF (hanzi | pinyin | level(pos) | vietnamese columns)
// into structured dictionary_words rows, and writes:
//   scripts/output/<name>.sql          - idempotent INSERT statements to run in Supabase
//   scripts/output/<name>.review.txt   - lines that couldn't be confidently parsed
//
// The PDF's own level column (A1, A2, B, C...) is used directly per-row — no page-range
// logic is needed. The band is derived from the level's leading letter (A1/A2 -> band "A").
//
// Usage: node scripts/import-dictionary-pdf.js "<path-to-pdf>" [output-name]
//   requires the `pdftotext` binary (poppler-utils) on PATH — dev-time only, not a
//   runtime app dependency.

const { execFileSync } = require('child_process')
const fs = require('fs')
const path = require('path')

const pdfPath = process.argv[2]
const outputName = process.argv[3] || path.basename(pdfPath, path.extname(pdfPath)).toLowerCase().replace(/[^a-z0-9]+/g, '-')

if (!pdfPath) {
  console.error('Usage: node scripts/import-dictionary-pdf.js <pdf-path> [output-name]')
  process.exit(1)
}

const OUTPUT_DIR = path.join(__dirname, 'output')
fs.mkdirSync(OUTPUT_DIR, { recursive: true })

const HANZI_RANGE = '\\u4e00-\\u9fff'
const LEVEL_RE = /\b((?:A1|A2|B1|B2|C1|C2|[ABCZ]))\b(?:\s*\(([A-Za-z]+)\))?/
const HANZI_RE = new RegExp(`^([${HANZI_RANGE}（）(][${HANZI_RANGE}（）()]*)`)

function parseLine(line) {
  const trimmed = line.trim()
  if (!trimmed) return null

  const levelMatch = trimmed.match(LEVEL_RE)
  if (!levelMatch) return null // no recognizable level tag -> not a data row (title/header/blank)

  const before = trimmed.slice(0, levelMatch.index).trim()
  const after = trimmed.slice(levelMatch.index + levelMatch[0].length).trim()
  const level = levelMatch[1]
  const pos = levelMatch[2] || null
  const band = level[0]

  const hanziMatch = before.match(HANZI_RE)
  let hanzi = ''
  let pinyin = ''
  if (hanziMatch) {
    hanzi = hanziMatch[1].trim()
    pinyin = before.slice(hanziMatch[0].length).trim()
  } else {
    pinyin = before.trim()
  }

  return { hanzi, pinyin, level, band, pos, vietnamese: after }
}

function main() {
  console.log('Extracting text via pdftotext...')
  const text = execFileSync('pdftotext', ['-table', '-enc', 'UTF-8', pdfPath, '-'], {
    maxBuffer: 1024 * 1024 * 64,
  }).toString('utf-8')

  const lines = text.split('\n')
  const entries = []
  const reviewLines = []
  let lastEntry = null

  for (const rawLine of lines) {
    const parsed = parseLine(rawLine)
    if (!parsed) continue

    if (parsed.hanzi && parsed.pinyin) {
      // Full row: a new dictionary entry.
      const entry = {
        hanzi: parsed.hanzi,
        pinyin: parsed.pinyin,
        level: parsed.level,
        band: parsed.band,
        pos: parsed.pos,
        vietnamese: parsed.vietnamese,
      }
      entries.push(entry)
      lastEntry = entry
    } else if (parsed.vietnamese) {
      // Continuation row: extra POS/meaning for the previous entry (blank hanzi/pinyin,
      // caused by a wrapped table cell in the source PDF).
      if (lastEntry) {
        if (!lastEntry.vietnamese) lastEntry.vietnamese = parsed.vietnamese
        else lastEntry.vietnamese += '; ' + parsed.vietnamese
      } else {
        reviewLines.push(rawLine)
      }
    } else {
      // Level tag with neither hanzi/pinyin nor meaning — nothing recoverable, skip silently
      // unless it looks like it was meant to carry data (has parso content besides level/pos).
      if (rawLine.trim() !== `${parsed.level}${parsed.pos ? ` (${parsed.pos})` : ''}`) {
        reviewLines.push(rawLine)
      }
    }
  }

  // Flag entries that ended up with no Vietnamese meaning at all — likely wrapped
  // across more lines than this parser reconstructed; needs a manual look.
  const incomplete = entries.filter((e) => !e.vietnamese)
  for (const e of incomplete) {
    reviewLines.push(`[NO MEANING] ${e.hanzi} ${e.pinyin} (${e.level})`)
  }

  console.log(`Parsed ${entries.length} entries (${incomplete.length} missing a meaning).`)
  console.log(`Review lines: ${reviewLines.length}`)

  const byLevel = {}
  for (const e of entries) byLevel[e.level] = (byLevel[e.level] || 0) + 1
  console.log('By level:', byLevel)

  const escapeSql = (s) => s.replace(/'/g, "''")
  const sqlLines = [
    `-- Generated by scripts/import-dictionary-pdf.js from ${path.basename(pdfPath)}`,
    `-- ${entries.length} entries. Run this in the Supabase SQL editor.`,
    'INSERT INTO public.dictionary_words (band, level, hanzi, pinyin, vietnamese, pos, order_index) VALUES',
  ]
  const valueRows = entries.map((e, i) => {
    const pos = e.pos ? `'${escapeSql(e.pos)}'` : 'NULL'
    return `  ('${escapeSql(e.band)}', '${escapeSql(e.level)}', '${escapeSql(e.hanzi)}', '${escapeSql(e.pinyin)}', '${escapeSql(e.vietnamese || '')}', ${pos}, ${i})`
  })
  sqlLines.push(valueRows.join(',\n') + '\nON CONFLICT (level, hanzi, pinyin, vietnamese) DO NOTHING;')

  const sqlPath = path.join(OUTPUT_DIR, `${outputName}.sql`)
  const reviewPath = path.join(OUTPUT_DIR, `${outputName}.review.txt`)
  fs.writeFileSync(sqlPath, sqlLines.join('\n'))
  fs.writeFileSync(reviewPath, reviewLines.join('\n'))

  console.log('Wrote', sqlPath)
  console.log('Wrote', reviewPath)
}

main()
