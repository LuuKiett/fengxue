// Builds scripts/output/tocfl8000-seed.sql from scripts/output/tocfl8000-matched.json
// (produced by extract-tocfl8000.js -> match-tocfl8000-translations.js ->
// patch-tocfl8000-manual.js). ON CONFLICT (level, hanzi, pinyin) DO UPDATE, safe to re-run.
//
// Usage: node scripts/build-tocfl8000-seed.js
const fs = require('fs')
const path = require('path')

const escapeSql = (s) => String(s).replace(/'/g, "''")
const sqlStr = (s) => (s === null || s === undefined || s === '' ? 'NULL' : `'${escapeSql(s)}'`)

function main() {
  const words = JSON.parse(fs.readFileSync(path.join(__dirname, 'output', 'tocfl8000-matched.json'), 'utf-8'))

  const lines = []
  lines.push('-- Auto-generated by scripts/build-tocfl8000-seed.js. Do not edit by hand.')
  lines.push(
    'INSERT INTO public.tocfl8000_words (level, context, hanzi, pinyin, vietnamese, pos, example_hanzi, example_pinyin, example_vietnamese, order_index) VALUES'
  )

  const rows = words.map((w) => {
    return `(${sqlStr(w.level)}, ${sqlStr(w.context)}, ${sqlStr(w.hanzi)}, ${sqlStr(w.pinyin)}, ${sqlStr(w.vietnamese)}, ${sqlStr(w.pos)}, ${sqlStr(w.example_hanzi)}, ${sqlStr(w.example_pinyin)}, ${sqlStr(w.example_vietnamese)}, ${w.order_index})`
  })
  lines.push(rows.join(',\n') + '')

  lines.push(`ON CONFLICT (level, hanzi, pinyin) DO UPDATE SET
  context = EXCLUDED.context,
  vietnamese = EXCLUDED.vietnamese,
  pos = EXCLUDED.pos,
  example_hanzi = EXCLUDED.example_hanzi,
  example_pinyin = EXCLUDED.example_pinyin,
  example_vietnamese = EXCLUDED.example_vietnamese,
  order_index = EXCLUDED.order_index;`)

  const outPath = path.join(__dirname, 'output', 'tocfl8000-seed.sql')
  fs.writeFileSync(outPath, lines.join('\n') + '\n')
  console.log('Wrote', outPath, '-', words.length, 'rows')
}

main()
